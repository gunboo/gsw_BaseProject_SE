"""Author the five-village test world while preserving the original core asset."""

from pathlib import Path
import importlib.util
import math
import random
import re
import shutil

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "SimpleGame/Data"
WIDTH, HEIGHT = 338, 164
OFFSET_Y = 70
CORE = DATA / "village_core.map"
CORE_PROFILES = DATA / "village_core_npcs.tsv"
LAYOUT_SLOTS_PER_VILLAGE = 20


def main():
	if not CORE.exists():
		assert "SIZE 88 72" in (DATA / "village.map").read_text(encoding="utf-8")
		shutil.copyfile(DATA / "village.map", CORE)
		shutil.copyfile(DATA / "village_npcs.tsv", CORE_PROFILES)
	lines = CORE.read_text(encoding="utf-8").splitlines()
	start = lines.index("TILES") + 1
	rng = random.Random(20261021)
	grid = [[rng.choices("T.,to", [62, 23, 8, 5, 2])[0] for _ in range(WIDTH)] for _ in range(HEIGHT)]
	for y in range(72):
		grid[y + OFFSET_Y][:88] = list(lines[start + y])
	props, elevations, original = [], [], {}
	section = None
	for line in lines[start + 72:]:
		if not line or line.startswith("#"):
			continue
		fields = line.split()
		if fields[0] in ("ELEVATIONS", "PROPS", "NPCS"):
			section = fields[0]
		elif fields[0] == "PLAYER":
			player = float(fields[1]), float(fields[2]) + OFFSET_Y
		elif section == "ELEVATIONS":
			fields[2] = str(int(fields[2]) + OFFSET_Y)
			elevations.append(" ".join(fields))
		elif section == "PROPS":
			fields[2] = str(float(fields[2]) + OFFSET_Y)
			props.append(" ".join(fields))
		elif section == "NPCS":
			original[fields[0]] = float(fields[1]), float(fields[2]) + OFFSET_Y
	towns = [line.split() for line in (DATA / "settlements.tsv").read_text(encoding="utf-8").splitlines()
		if line and not line.startswith("#")]
	for i, town in enumerate(towns):
		cx, cy = map(float, town[2:4])
		if i != 0:
			for y in range(int(cy) - 17, int(cy) + 18):
				for x in range(int(cx) - 17, int(cx) + 18):
					grid[y][x] = "." if rng.random() < .8 else ","
			for dx, dy, variant in [(-14, -13, 0), (9, -13, 1), (-14, 8, 2), (9, 8, 0)]:
				props.append(f"house {cx + dx} {cy + dy} 4 3 {variant}")
			props.append(f"shrine {cx - 2} {cy - 16} 4 2 0")
			for dx, dy in [(-10, -2), (10, -2), (-10, 7), (10, 7)]:
				props.append(f"lantern {cx + dx} {cy + dy} 0 0 0")
	# The flat plaza-to-plaza road is 62 cells: 20 seconds at 3.1 cells/second.
	for y in range(96, 122):
		for x in range(44, 294):
			if x >= 88:
				grid[y][x] = "." if rng.random() < .9 else ","
	for y in range(107, 111):
		for x in range(44, 294):
			grid[y][x] = ":"
	for y in range(HEIGHT):
		grid[y][0] = grid[y][-1] = "T"
	grid[0] = grid[-1] = ["T"] * WIDTH
	profiles = {f[0]: f for line in CORE_PROFILES.read_text(encoding="utf-8").splitlines()
		if line and not line.startswith("#") for f in [line.split()]}
	central = list(original)[:8] + ["merchant_rice", "merchant_medicine", "merchant_relic", "priest_memorial",
		"guard_west", "guard_east", "porter", "caretaker", "scribe", "relief_worker", "charitable_farmer", "grave_keeper"]
	remaining = [name for name in original if name not in central]
	residents = []
	for town_index, town in enumerate(towns):
		ids = central if town_index == 0 else []
		if town_index == 3:
			ids = remaining[:4]
		elif town_index == 4:
			ids = remaining[4:]
		ids = list(ids)
		# Keep authored positions stable when the active population changes.
		while len(ids) < LAYOUT_SLOTS_PER_VILLAGE:
			ids.append(f"{town[0]}_resident_{len(ids) + 1:02d}")
		for index, name in enumerate(ids):
			template = profiles[name] if name in profiles else profiles[
				["merchant_rice", "porter", "farmer", "guard_west", "monk", "priest_memorial", "scribe", "charitable_farmer"][index % 8]]
			fields = list(template)
			fields[0] = name
			courier = name in ("merchant_rice", "porter") if town_index == 0 else index in (8, 9)
			if courier:
				fields[1:7] = ["merchant", "6", "3.1", "carry", "1", "0"]
			cx, cy = map(float, town[2:4])
			position = original[name] if town_index == 0 and index < 8 else (
				cx + (-7, -2, 3, 8)[index % 4], cy + (-7, -3, 1, 5, 9)[index // 4])
			if courier:
				position = cx + (0 if index % 2 == 0 else 2), cy + 2
			residents.append([fields + [town[0], "1" if courier else "0"], position, template[0], town[1]])

	def write_map():
		out = ["# Five connected settlements; generated by Tools/generate_settlements.py.",
			f"SIZE {WIDTH} {HEIGHT}", "TILES"] + ["".join(row) for row in grid]
		out += ["ELEVATIONS"] + elevations + ["PROPS"] + props + ["NPCS"]
		out += [f"{fields[0]} {position[0]} {position[1]}" for fields, position, _, _ in residents]
		out += [f"PLAYER {player[0]} {player[1]}"]
		(DATA / "village.map").write_text("\n".join(out) + "\n", encoding="utf-8")

	write_map()
	spec = importlib.util.spec_from_file_location("village_geometry", ROOT / "Tools/validate_village.py")
	module = importlib.util.module_from_spec(spec)
	spec.loader.exec_module(module)
	village = module.Village(DATA / "village.map")
	occupied = []
	for record in residents:
		fields, position, _, _ = record
		candidates = [position]
		town = next(t for t in towns if t[0] == fields[-2])
		cx, cy = map(float, town[2:4])
		candidates += sorted(((x + .5, y + .5) for y in range(int(cy) - 12, int(cy) + 13)
			for x in range(int(cx) - 12, int(cx) + 13)), key=lambda q: math.dist(q, position))
		for candidate in candidates:
			x, y = candidate
			if math.dist(candidate, (cx, cy)) > 13.5 or village.blocked(x, y):
				continue
			if not village.can_move(candidate, (math.floor(x) + .5, math.floor(y) + .5)):
				continue
			if any(math.dist(candidate, other) < 1.1 for other in occupied):
				continue
			if fields[4] == "garden":
				fx, fy = map(float, fields[5:7]); length = math.hypot(fx, fy)
				target = x + fx / length * .65, y + fy / length * .65
				if abs(village.elevation(*target) - village.elevation(x, y)) > .1 or any(
					village.blocked(target[0] + dx, target[1] + dy, .04) for dx in (-.375, .375) for dy in (-.375, .375)):
					continue
			record[1] = candidate
			occupied.append(candidate)
			break
		else:
			raise AssertionError(f"No valid workplace for {fields[0]}")
	write_map()
	from validate_settlements import geometry
	audit = geometry()
	reached = audit.reachable()
	sealed = 0
	for y in range(HEIGHT):
		for x in range(WIDTH):
			if x < 88 and OFFSET_Y <= y < OFFSET_Y + 72:
				continue
			if (x, y) not in reached and not audit.blocked(x + .5, y + .5):
				grid[y][x] = "T"
				sealed += 1
	roster = [line.split() for line in (DATA / "village_roster.tsv").read_text(encoding="utf-8").splitlines()
		if line and not line.startswith("#")]
	assert all(len(row) == 2 for row in roster)
	active = {row[0]: row[1] for row in roster}
	assert len(active) == len(roster), "Duplicate active resident"
	residents = [record for record in residents if record[0][0] in active]
	assert {record[0][0] for record in residents} == active.keys(), "Unknown roster resident"
	assert all(record[0][-2] == active[record[0][0]] for record in residents), "Roster home village disagrees"
	write_map()
	(DATA / "village_npcs.tsv").write_text("# id behavior radius speed occupation facingX facingY homeVillage courier\n"
		+ "\n".join("\t".join(r[0]) for r in residents) + "\n", encoding="utf-8")
	dialogue_path = DATA / "dialogue.txt"
	dialogue = dialogue_path.read_text(encoding="utf-8-sig")
	dialogue = dialogue.split("# BEGIN GENERATED SETTLEMENT DIALOGUE")[0].rstrip() + "\n"
	blocks = {m[1]: m[2] for m in re.finditer(r"^@([^\n]+)\n(.*?)(?=^@|\Z)", dialogue, re.M | re.S)}
	dialogue += "\n# BEGIN GENERATED SETTLEMENT DIALOGUE\n"
	for fields, _, template, town_name in residents:
		if fields[0] not in blocks:
			body = blocks.get(template, "").split("\n#")[0].strip()
			body = re.sub(r"^\$[^\n]+", "$" + town_name + " " + fields[0].split("_")[-1], body, count=1)
			dialogue += f"\n@{fields[0]}\n{body}\n"
	for town in towns:
		dialogue += f"\n@town_{town[0]}\n{town[1]}\n"
	for key, name in [("calm", "평온"), ("hopeful", "희망"), ("tense", "긴장"), ("threatened", "위협")]:
		dialogue += f"\n@mood_{key}\n{name}\n"
	news = [
		("road_watch", "등불마을 경비가 길을 지키고 있대요.", "요괴가 나타나면 가까운 마을로 돌아가세요."),
		("rice_convoy", "장터마을에 쌀 수레가 들어왔답니다.", "길이 안전해지면 다른 마을에도 나눌 수 있겠지요."),
		("memorial", "기도마을에서는 희생자 이름을 기록한대요.", "이름을 잊지 않는 것이 산 사람의 몫이지요."),
		("ferry_open", "나루마을에서 물자 운송을 다시 시작했대요.", "장사꾼들이 직접 길을 오가며 전한 소식이에요."),
		("bandit_warning", "변경마을 바깥길에 산적이 있다는군요.", "검을 뽑기 전에 돌아갈 길부터 살펴보세요."),
	]
	for key, first, second in news:
		dialogue += f"\n@rumor_{key}\n$마을 사람\n{first}\n{second}\n"
	dialogue_path.write_text(dialogue, encoding="utf-8")
	print(f"Authored {WIDTH}x{HEIGHT}, five villages, {len(residents)} residents; sealed {sealed} isolated extension cells.")


if __name__ == "__main__":
	main()
